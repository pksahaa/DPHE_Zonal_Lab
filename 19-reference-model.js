// ===== 19-reference-model.js =====
// ============================================================================
// REFERENCE MODEL — samples arrive from three kinds of source:
//   1. DPHE (own water points)              — bulk, always has an office
//      letter + reference no.
//   2. Private/Public institution            — bulk (smaller than DPHE),
//      also comes with a letter + reference no.
//   3. Walk-in (public/private individual)   — usually 1-2 samples, often
//      NO reference no. at all.
//
// A "Reference" is that source paperwork, promoted from a loose free-text
// `Sample.batchRef` string into a real record: source type, letter date,
// organization, contact. One Reference can cover many Samples (DPHE's 50
// samples = 1 Reference). Reporting is done BY Reference, not by whichever
// Sub-Batch happened to test the samples (see 16-sub-batch.js / 17-report-
// generator.js) — this file is what that Reference actually is.
//
// Pure-data + pure-function module, same shape as 20-sample-model.js, so it
// can be unit tested / reused without React.
// ============================================================================

const REFERENCE_SOURCE_TYPES = [{
  key: "dphe",
  label: "DPHE",
  icon: "clipboard"
}, {
  key: "other_govt",
  label: "Other Govt. organization",
  icon: "clipboard"
}, {
  key: "private_org",
  label: "Private organization",
  icon: "beaker"
}, {
  key: "walkin",
  label: "Walk-in-Client",
  icon: "user"
}, {
  key: "others",
  label: "Others (Pls Specify)",
  icon: "user"
}];
// Client Type — a separate axis from Client Source (e.g. a DPHE sample can
// be an ADP project sample, a Calamity response sample, etc.).
const CLIENT_TYPES = ["ADP", "Non-ADP", "Calamity", "Monitoring", "VVIP", "Others (Pls Specify)"];
// Reference (source) types that always carry office paperwork — Ref/Memo
// No., Organization Name, Letter Date, Contact Person, Contact Phone, and
// Notes are collected for all of these (not just DPHE), since any of them
// might show up with a letter.
const REFERENCE_TYPES_WITH_PAPERWORK = ["dphe", "private_org", "other_govt"];
function referenceSourceMeta(key) {
  // "institution" is the pre-Client-Type-redesign key — treat it the same
  // as Private Organization rather than losing the distinction.
  const resolvedKey = key === "institution" ? "private_org" : key;
  return REFERENCE_SOURCE_TYPES.find(s => s.key === resolvedKey) || REFERENCE_SOURCE_TYPES[3];
}
// Tracking No. is entered by hand at registration time and must be unique
// across every Reference (Client Part entry) — this is the check used at
// submit time, in both the main registration window and the bulk-upload
// Client Part popup.
function isTrackingNoTaken(trackingNo, existingReferences, excludeReferenceId) {
  const clean = (trackingNo || "").trim().toLowerCase();
  if (!clean) return false;
  return (existingReferences || []).some(r => r.id !== excludeReferenceId && (r.trackingNo || "").trim().toLowerCase() === clean);
}

// ---- internal ref no. generator — for walk-ins (or any source) that show
// up with no office letter/reference no. of their own, so every Reference
// is still trackable. Format deliberately distinct from a real office memo
// no. so nobody mistakes it for one on a printed report. ----
function generateInternalRefNo(existingReferences, dateStr) {
  const year = (dateStr || todayStr()).slice(0, 4);
  const nums = (existingReferences || []).filter(r => (r.refNo || "").startsWith(`INT-${year}-`)).map(r => Number(r.refNo.split("-")[2]) || 0);
  const next = (nums.length ? Math.max(...nums) : 0) + 1;
  return `INT-${year}-${String(next).padStart(6, "0")}`;
}

// ---- Tracking No. auto-generator — for the registration form's
// [Generate] button, so a Tracking No. can be produced automatically
// instead of always typed by hand. Sequence is per-year, distinct prefix
// from the internal Ref No. generator so the two can't be confused. Still
// runs through isTrackingNoTaken() at submit time like any manually typed
// value, so a collision (e.g. two people generating at once) is caught. ----
function generateTrackingNo(existingReferences, dateStr) {
  const year = (dateStr || todayStr()).slice(0, 4);
  const prefix = `TRK-${year}-`;
  const nums = (existingReferences || []).filter(r => (r.trackingNo || "").startsWith(prefix)).map(r => Number(r.trackingNo.split("-")[2]) || 0);
  let next = (nums.length ? Math.max(...nums) : 0) + 1;
  let candidate = `${prefix}${String(next).padStart(6, "0")}`;
  while (isTrackingNoTaken(candidate, existingReferences)) {
    next += 1;
    candidate = `${prefix}${String(next).padStart(6, "0")}`;
  }
  return candidate;
}

// ---- factory ----
function createReference(fields, existingReferences, user) {
  const now = new Date().toISOString();
  const sourceType = REFERENCE_SOURCE_TYPES.some(s => s.key === fields.sourceType) ? fields.sourceType : "walkin";
  const typedRefNo = (fields.refNo || "").trim();
  const isAutoGenerated = !typedRefNo;
  return {
    id: uid("ref"),
    refNo: typedRefNo || generateInternalRefNo(existingReferences, fields.letterDate),
    isAutoGenerated,
    sourceType,
    sourceTypeOther: fields.sourceTypeOther || "",
    clientType: CLIENT_TYPES.includes(fields.clientType) ? fields.clientType : "",
    clientTypeOther: fields.clientTypeOther || "",
    trackingNo: (fields.trackingNo || "").trim(),
    organizationName: fields.organizationName || "",
    letterDate: fields.letterDate || "",
    // "Client Name" / "Client Contact No." in the Client Part form —
    // contactPerson/contactPhone field names kept for backward
    // compatibility with existing data.
    contactPerson: fields.contactPerson || "",
    contactPhone: fields.contactPhone || "",
    address: fields.address || "",
    createdAt: now,
    createdBy: user?.name || "Unknown",
    updatedAt: now
  };
}

// ---- edit (registration-detail correction, same philosophy as editSample —
// no history log needed here since a Reference has no status/custody of its
// own; it's descriptive paperwork metadata, not a tracked physical item) ----
const REFERENCE_EDITABLE_FIELDS = ["refNo", "sourceType", "sourceTypeOther", "clientType", "clientTypeOther", "trackingNo", "organizationName", "letterDate", "contactPerson", "contactPhone", "address", "notes"];
function editReference(reference, patch) {
  const cleanPatch = {};
  REFERENCE_EDITABLE_FIELDS.forEach(field => {
    if (field in patch) cleanPatch[field] = patch[field];
  });
  const nextRefNo = "refNo" in cleanPatch ? (cleanPatch.refNo || "").trim() : reference.refNo;
  return {
    ...reference,
    ...cleanPatch,
    refNo: nextRefNo || reference.refNo,
    // once a real ref no. is typed in, it's no longer "auto-generated"
    isAutoGenerated: nextRefNo ? false : reference.isAutoGenerated,
    updatedAt: new Date().toISOString()
  };
}

// ---- display helpers ----
function referenceDisplayLabel(reference) {
  if (!reference) return "";
  const org = reference.organizationName ? ` — ${reference.organizationName}` : "";
  const tracking = reference.trackingNo ? ` [${reference.trackingNo}]` : "";
  return `${reference.refNo}${org}${tracking}`;
}
function findReferenceById(references, id) {
  return (references || []).find(r => r.id === id) || null;
}

// ---- migration: existing installs have samples with a loose `batchRef`
// string and no `referenceId` at all. Runs once (idempotent — a sample that
// already has a referenceId is left untouched) on app load, turning every
// distinct batchRef value into a real Reference record so nothing existing
// data-wise is lost, and every sample ends up pointing at a proper
// Reference. Source type defaults to "institution" (the safest bulk-source
// guess) with a note flagging it for the admin to correct/fill in — better
// than silently guessing DPHE vs walk-in from a bare string. ----
function migrateBatchRefsToReferences(samples, existingReferences) {
  const references = [...(existingReferences || [])];
  const byRefNo = new Map(references.map(r => [r.refNo, r]));
  const nextSamples = (samples || []).map(sample => {
    if (sample.referenceId) return sample;
    // no batchRef at all: this was an individually-registered sample —
    // still worth giving it a Reference so referenceId is never blank.
    const rawRef = (sample.batchRef || "").trim();
    let ref = rawRef ? byRefNo.get(rawRef) : null;
    if (!ref) {
      ref = createReference({
        refNo: rawRef,
        sourceType: rawRef ? "private_org" : "walkin",
        notes: rawRef ? "Auto-migrated from legacy Batch Ref field — please verify source type and add organization/contact details." : "Auto-migrated — individually registered sample with no batch reference; verify source type."
      }, references, {
        name: "System (migration)"
      });
      references.push(ref);
      if (rawRef) byRefNo.set(rawRef, ref);
    }
    return {
      ...sample,
      referenceId: ref.id
    };
  });
  return {
    references,
    samples: nextSamples
  };
}
